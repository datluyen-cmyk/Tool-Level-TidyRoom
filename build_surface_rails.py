"""Estimate short placement rails from the original layouts and artwork."""

import base64
import gzip
import json
import re
from math import cos, sin, radians, hypot
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parent
DRAPED = re.compile(r'^(1-(4|11|15|19|20)|12-4|74-[1-8]|107-6|611-1)$')


def contrast(pixels, x, y, nx, ny):
    """Signed RGB difference across a candidate edge in the downsized image."""
    a = pixels[round(x - nx * 2), round(y - ny * 2)]
    b = pixels[round(x + nx * 2), round(y + ny * 2)]
    return tuple(j - i for i, j in zip(a, b))


def rail(pixels, size, x, y, width, height, angle):
    def sample(t, off):
        px, py = x + t * dx + off * nx, y + t * dy + off * ny
        if not (3 <= px < size[0] - 4 and 3 <= py < size[1] - 4):
            return (0, 0, 0)
        return contrast(pixels, px, py, nx, ny)

    best = None
    for tilt in (0, -7, 7, -13, 13):
        dx, dy = cos(radians(angle + tilt)), -sin(radians(angle + tilt))
        nx, ny = -dy, dx
        for off in (-.26, -.18, -.10, 0, .10, .18, .26):
            offset = off * height
            profile = [sample(width * t, offset) for t in (-.28, -.14, 0, .14, .28)]
            direction = tuple(sum(p[i] for p in profile) / len(profile) for i in range(3))
            peak = hypot(*direction)
            if peak < 24:
                continue
            unit = tuple(v / peak for v in direction)
            response = lambda rgb: sum(v * u for v, u in zip(rgb, unit))
            if sum(response(p) >= 14 for p in profile) < 4:
                continue
            score = peak - abs(off) * 15 - abs(tilt) * .5
            valid = []
            for sign in (-1, 1):
                extent = 0
                for step in (.18, .32, .46, .60, .74):
                    t = sign * step * width
                    if sum(response(sample(t + width * dt, offset)) >= max(12, peak * .30)
                           for dt in (-.16, 0, .16)) < 2:
                        break
                    extent = t
                valid.append(extent)
            if max(map(abs, valid)) >= width * .32 and (best is None or score > best[0]):
                best = (score, dx, dy, *valid)
    return best


def main():
    def read(name):
        return (ROOT / 'data' / name).read_text(encoding='utf-8')

    catalog = json.loads(read('catalog.js').split('=', 1)[1].strip().removesuffix(';'))
    addon = json.loads(re.search(r'const additions\s*=\s*({.*?});\s*\n', read('tidy57-addon.js'), re.S)[1])
    keys = lambda rows: {('roomsort' if row.get('palette') else row['family'], row['id']): row for row in rows}
    items = keys(catalog['items'] + addon['items'])
    backgrounds = keys(catalog['backgrounds'] + addon['backgrounds'])
    encoded = re.search(r'=\s*"([A-Za-z0-9+/=]+)"', read('gdd-137.js'))[1]
    pack = json.loads(gzip.decompress(base64.b64decode(encoded)))
    models = {}
    for level in pack['levels']:
        poses = [(i, it) for i, it in enumerate(level['content']) if DRAPED.fullmatch(it['id'])]
        if not poses:
            continue
        bg = backgrounds[level.get('bgSet', 'roomsort'), level['bg']]
        file = ROOT / bg.get('url', bg['path'])
        if not file.is_file():
            continue
        with Image.open(file) as source:
            image = source.convert('RGB')
        image.thumbnail((520, 520), Image.Resampling.LANCZOS)
        width, height = level.get('bgSize', (bg['w'], bg['h']))
        sx, sy = image.width / width, image.height / height
        candidates = []
        for i, it in poses:
            art = items[it.get('set', level.get('itemSet', 'roomsort')), it['id']]
            iw, ih = it.get('size', art.get('native', (art['w'], art['h'])))
            x, y = image.width / 2 + it['x'] * sx, image.height / 2 - it['y'] * sy
            result = rail(image.load(), image.size, x, y, iw * abs(it.get('scaleX', 1)) * sx,
                          ih * abs(it.get('scaleY', 1)) * sy, it.get('angle', 0))
            if result is None:
                continue
            score, dx, dy, lo, hi = result
            points = [[round(it['x'] + dx * t / sx, 3), round(it['y'] - dy * t / sy, 3)] for t in (lo, hi)]
            candidates.append([i, points, round(score)])
        if candidates:
            models[level['key']] = candidates
    output = ROOT / 'data' / 'surface-rails.js'
    output.write_text('// Generated by build_surface_rails.py. Filtered estimates, not hand-marked edges.\n'
                      'window.TIDY_SURFACE_RAILS = ' + json.dumps(models, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{len(models)} backgrounds, {sum(map(len, models.values()))} candidate edge segments')


if __name__ == '__main__':
    main()
